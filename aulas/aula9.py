#Operadores aritméticos

adicao = 10 + 10
print('Adição', adicao)

subtracao = 10 - 5
print('Subtração', subtracao)

multiplicacao = 10 * 10
print('Multiplicação:', multiplicacao)

divisao = 10 / 2
print('Divisão:', divisao)

dvisao_inteira = 10 // 2
print('Divisão Inteira', dvisao_inteira)

exponenciacao = 2 ** 10
print('Exponenciação', exponenciacao)

modulo = 25 % 5
print('Modulo', modulo)